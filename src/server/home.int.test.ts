import { randomUUID } from "node:crypto";

import { afterAll, afterEach, beforeEach, describe, expect, it, vi } from "vitest";

import { db } from "@/lib/db";
import { accountSchema } from "@/lib/validation/accounts";
import { cardSchema } from "@/lib/validation/cards";
import { entrySchema, transferSchema } from "@/lib/validation/transactions";
import { createAccount } from "@/server/accounts";
import { createCard } from "@/server/cards";
import { homeSummary } from "@/server/home";
import { dashboardMetrics } from "@/server/metrics";
import { createSubscriptionRule } from "@/server/onboarding";
import { ensurePersonalSpace } from "@/server/spaces";
import { createTransaction, createTransfer } from "@/server/transactions";
import { resetDatabase } from "@/test/db";

beforeEach(resetDatabase);
afterEach(() => vi.useRealTimers());
afterAll(() => db.$disconnect());

let minute = 0;
function on(day = "2026-11-15") {
  vi.useFakeTimers({ toFake: ["Date"] });
  minute += 1;
  vi.setSystemTime(new Date(`${day}T15:${String(minute % 60).padStart(2, "0")}:00Z`));
}

async function space(email: string) {
  on();
  const user = await db.user.create({ data: { name: "Ana Teste", email } });
  const { id: spaceId } = await ensurePersonalSpace(user.id);
  const account = await createAccount(
    spaceId,
    accountSchema.parse({
      name: "Banco Azul",
      color: "blue",
      initialBalance: "1.000,00",
      initialBalanceDate: "2026-10-01",
    }),
  );
  if (!account.ok) throw new Error(account.error);
  const other = await createAccount(
    spaceId,
    accountSchema.parse({
      name: "Banco Verde",
      color: "green",
      initialBalance: "0,00",
      initialBalanceDate: "2026-10-01",
    }),
  );
  if (!other.ok) throw new Error(other.error);
  return { userId: user.id, spaceId, accountId: account.account.id, otherId: other.account.id };
}

type Space = Awaited<ReturnType<typeof space>>;

async function card(s: Space, name = "Cartão Roxo") {
  const created = await createCard(
    s.spaceId,
    cardSchema.parse({ name, accountId: s.accountId, closingDay: 3, dueDay: 10 }),
  );
  if (!created.ok) throw new Error(created.error);
  return created.card.id;
}

async function entry(s: Space, input: Record<string, unknown>) {
  const result = await createTransaction(
    s.spaceId,
    s.userId,
    randomUUID(),
    entrySchema.parse({
      type: "EXPENSE",
      method: "PIX",
      accountId: input.cardId ? undefined : s.accountId,
      date: "2026-11-15",
      ...input,
    }),
  );
  if (!result.ok) throw new Error(result.error);
}

describe("homeSummary", () => {
  it("CA7: a fatura aberta de cada cartão, os últimos lançamentos e o gasto de hoje, só do espaço", async () => {
    const s = await space("ana@example.com");
    const roxo = await card(s);
    const verde = await card(s, "Cartão Verde");
    // A subscription created in October, charging on the 15th: today's charge is generated by
    // the home itself.
    on("2026-10-01");
    const rule = await createSubscriptionRule(s.spaceId, s.userId, {
      counterparty: "Streamflix",
      amountCents: 3_990,
      dayOfMonth: 15,
      method: "PIX",
      accountId: s.accountId,
      cardId: null,
      categoryId: null,
      description: null,
    });
    if (!rule.ok) throw new Error(rule.error);
    on();
    // Today: 45,00 by Pix at the market and 30,00 on credit. Yesterday: 20,00.
    await entry(s, { amountCents: 2_000, date: "2026-11-14" });
    await entry(s, { amountCents: 4_500, counterparty: "Mercado Bom Preço" });
    await entry(s, { amountCents: 3_000, method: "CREDIT", cardId: roxo });
    // 3 × 100,00 from 10/11 (after the closing on the 3rd): the 1st on the invoice due 10/12,
    // the next ones in December and January (after today: not in the latest list).
    await entry(s, {
      amountCents: 30_000,
      date: "2026-11-10",
      method: "CREDIT",
      cardId: roxo,
      installments: 3,
    });
    // What isn't today's expense: an income, a transfer, a balance adjustment.
    await entry(s, { type: "INCOME", amountCents: 100_000 });
    await createTransfer(
      s.spaceId,
      s.userId,
      randomUUID(),
      transferSchema.parse({
        amountCents: 50_000,
        date: "2026-11-15",
        method: "PIX",
        accountId: s.accountId,
        toAccountId: s.otherId,
      }),
    );
    await db.transaction.create({
      data: {
        spaceId: s.spaceId,
        clientId: randomUUID(),
        createdById: s.userId,
        type: "EXPENSE",
        amountCents: 7_000,
        date: new Date("2026-11-15T00:00:00Z"),
        method: "PIX",
        accountId: s.accountId,
        adjustment: true,
      },
    });
    // Another space's expense of today.
    const other = await space("bia@example.com");
    await entry(other, { amountCents: 99_900 });

    on();
    const home = await homeSummary(s.spaceId);
    expect(home.today).toBe("2026-11-15");
    // The open invoice (due 10/12): 30,00 + the 1st installment of 100,00. The green card: zero.
    expect(home.cards).toEqual([
      { id: roxo, name: "Cartão Roxo", dueDate: "2026-12-10", totalCents: 13_000 },
      { id: verde, name: "Cartão Verde", dueDate: "2026-12-10", totalCents: 0 },
    ]);
    // The 5 latest up to today, newest registered first: the charge the home just generated,
    // the adjustment, the transfer, the income, the 30,00. The 45,00 and 14/11 don't fit.
    expect(home.recent).toHaveLength(5);
    expect(home.recent.every((i) => i.date === "2026-11-15")).toBe(true);
    expect(home.recent.map((i) => i.amountCents)).toEqual([3_990, 7_000, 50_000, 100_000, 3_000]);
    expect(home.subscriptions).toEqual({ monthlyCents: 3_990, yearlyCents: 47_880, count: 1 });

    expect(home.hasEntries).toBe(true);

    // With the metrics (task 25): today's expense, 45,00 + 30,00 + the subscription's 39,90; the
    // month's top counterparty, the market (Streamflix's 39,90 is less).
    const metrics = (await dashboardMetrics(s.spaceId, "2026-11"))!;
    expect(metrics.todayExpenseCents).toBe(11_490);
    expect(metrics.topCounterparty).toEqual({
      id: expect.any(String),
      name: "Mercado Bom Preço",
      totalCents: 4_500,
    });
    // A past month has no "today".
    expect((await dashboardMetrics(s.spaceId, "2026-10"))!.todayExpenseCents).toBeNull();
  });

  it("os últimos lançamentos não trazem parcelas com data depois de hoje", async () => {
    const s = await space("ana@example.com");
    const roxo = await card(s);
    await entry(s, {
      amountCents: 30_000,
      date: "2026-11-10",
      method: "CREDIT",
      cardId: roxo,
      installments: 3,
    });
    on();
    const home = await homeSummary(s.spaceId);
    expect(home.recent.map((i) => [i.date, i.installmentNumber])).toEqual([["2026-11-10", 1]]);
    expect(home.recent[0]!.installmentGroupCents).toBe(30_000);
  });

  it("um espaço novo: nada hoje, sem cartões, sem lançamentos", async () => {
    const s = await space("ana@example.com");
    // A transfer alone isn't an expense or income: the summary is still empty.
    await createTransfer(
      s.spaceId,
      s.userId,
      randomUUID(),
      transferSchema.parse({
        amountCents: 10_000,
        date: "2026-11-15",
        method: "PIX",
        accountId: s.accountId,
        toAccountId: s.otherId,
      }),
    );
    on();
    const home = await homeSummary(s.spaceId);
    expect(home).toMatchObject({
      cards: [],
      subscriptions: { monthlyCents: 0, yearlyCents: 0, count: 0 },
      hasEntries: false,
    });
    const metrics = (await dashboardMetrics(s.spaceId, "2026-11"))!;
    expect(metrics.todayExpenseCents).toBe(0);
    expect(metrics.topCounterparty).toBeNull();
    expect(home.recent).toHaveLength(1);
  });
});
